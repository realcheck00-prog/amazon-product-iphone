-- ============================================================================
-- Customer onboarding records.
--
-- Replaces the former card-oriented billing-details store. This table holds
-- ONLY the customer information a legitimate onboarding form needs:
--
--   * username              -- chosen by the customer, alphanumeric
--   * customer_reference    -- ISSUED BY THE DATABASE, never by the customer
--   * full name, email, phone, postal address
--   * date of birth (month + year) -- OPTIONAL, nullable, and only collected
--     because a customer record may need it; it is not required for this
--     business purpose and it is never used as proof of identity
--   * verification_status / verified_at / verification_reference -- the state
--     of the confirmation that our support team carries out by phone
--
-- NEVER store card numbers, CVVs, PINs, expiry dates, one-time codes,
-- passwords or any other credential. There is no column for them and no code
-- path that can write one.
--
-- Authorization model
-- -------------------
-- This is a guest checkout with no Supabase Auth session, so the table is
-- reached exactly like `public.orders`:
--   * RLS is enabled and NO policies are granted, and the `anon` /
--     `authenticated` table grants are revoked, so an anonymous client has no
--     direct access at all.
--   * The only writer is the `complete-onboarding` Edge Function, which
--     authorises the caller with the per-order capability token and connects
--     with the service-role key (never exposed to the browser).
--
-- Duplicate submissions
-- ---------------------
--   * `order_id` is UNIQUE, so one checkout produces at most one profile and
--     a retry returns the existing row instead of creating a second one.
--   * `username` is UNIQUE, so the same username cannot be claimed twice.
--
-- This migration is additive: it creates one new table and touches nothing
-- that already exists.
-- ============================================================================

create table if not exists public.customer_profiles (
  id uuid primary key default gen_random_uuid(),

  -- The public customer reference. It is generated by the database and is
  -- therefore assigned by the trusted backend, never chosen by the customer.
  -- The customer never types it and it is never taken from the request body.
  customer_reference text not null unique
    default ('CUST-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 10))),

  -- One onboarding record per order. UNIQUE makes repeated submissions of
  -- the same checkout idempotent.
  order_id uuid not null unique references public.orders (id) on delete cascade,

  -- Chosen by the customer. Lowercase alphanumeric. This is a LABEL, not
  -- proof of account ownership: it is never treated as a credential and it
  -- never grants access to anything on its own.
  username text not null unique,

  full_name text not null,
  email text not null,
  phone text not null,

  -- Optional. Only stored when the customer supplied it.
  birth_month smallint,
  birth_year smallint,

  address_line1 text not null,
  address_line2 text not null default '',
  city text not null,
  region text not null,
  postal_code text not null,
  country text not null,

  -- Manual confirmation by our support team. There is no automated
  -- verification in this application, so a new record always starts as
  -- 'pending_review' and is only marked 'confirmed' by staff.
  verification_status text not null default 'pending_review',
  verified_at timestamptz,
  -- Non-sensitive reference to the confirmation (ticket or call-log id).
  verification_reference text,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint customer_profiles_username_shape
    check (username ~ '^[a-z0-9]{3,32}$'),
  constraint customer_profiles_full_name_len
    check (char_length(btrim(full_name)) between 2 and 120),
  constraint customer_profiles_email_shape
    check (email ~* '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),
  constraint customer_profiles_phone_len
    check (char_length(btrim(phone)) between 5 and 40),
  constraint customer_profiles_birth_month_range
    check (birth_month is null or birth_month between 1 and 12),
  constraint customer_profiles_birth_year_range
    check (birth_year is null or birth_year between 1900 and 2100),
  constraint customer_profiles_address_line1_len
    check (char_length(btrim(address_line1)) between 1 and 200),
  constraint customer_profiles_address_line2_len
    check (char_length(address_line2) <= 120),
  constraint customer_profiles_city_len
    check (char_length(btrim(city)) between 1 and 120),
  constraint customer_profiles_region_len
    check (char_length(btrim(region)) between 1 and 120),
  constraint customer_profiles_postal_len
    check (char_length(btrim(postal_code)) between 1 and 20),
  constraint customer_profiles_country_len
    check (char_length(btrim(country)) between 2 and 64),
  constraint customer_profiles_verification_status_valid
    check (verification_status in ('pending_review', 'confirmed', 'rejected')),
  -- A confirmed record always carries the time it was confirmed.
  constraint customer_profiles_verified_at_present
    check (verification_status <> 'confirmed' or verified_at is not null)
);

comment on table public.customer_profiles is
  'Customer onboarding records. Written only by the complete-onboarding Edge Function (service role). No card or credential data is ever stored.';
comment on column public.customer_profiles.customer_reference is
  'Public customer reference, generated by the database. Never supplied by the customer.';
comment on column public.customer_profiles.username is
  'Lowercase alphanumeric label chosen by the customer. Not a credential and not proof of account ownership.';
comment on column public.customer_profiles.birth_month is
  'Optional birth month (1-12). Null when the customer did not provide it.';
comment on column public.customer_profiles.birth_year is
  'Optional birth year. Null when the customer did not provide it.';
comment on column public.customer_profiles.verification_status is
  'Confirmation state: pending_review (default), confirmed or rejected. Confirmation is carried out by our team by phone.';
comment on column public.customer_profiles.verification_reference is
  'Non-sensitive reference to the manual confirmation (ticket or call-log id).';

-- ----------------------------------------------------------------------------
-- Indexes
-- ----------------------------------------------------------------------------
create index if not exists customer_profiles_email_idx on public.customer_profiles (email);
create index if not exists customer_profiles_created_at_idx on public.customer_profiles (created_at desc);

-- ----------------------------------------------------------------------------
-- updated_at trigger
-- ----------------------------------------------------------------------------
drop trigger if exists customer_profiles_set_updated_at on public.customer_profiles;
create trigger customer_profiles_set_updated_at
  before update on public.customer_profiles
  for each row execute function public.set_updated_at();

-- ----------------------------------------------------------------------------
-- Row Level Security
-- ----------------------------------------------------------------------------
alter table public.customer_profiles enable row level security;

-- Intentionally no policies: anon/authenticated get no direct table access.
-- The service role (used inside Edge Functions) bypasses RLS.

-- Defence in depth: strip the default Supabase table grants too, so even a
-- future policy mistake could not hand this table to anonymous clients.
revoke all on table public.customer_profiles from anon, authenticated;

